export function ogcTlsOptions(hostname: string): tls.ConnectionOptions {
  const verification = { rejectUnauthorized: true, allowPartialTrustChain: false };
  if (hostname !== "opendata.gaiurb.pt") return verification;

  // Preserve configured/default roots on current Node releases. Older Node 20
  // releases expose only the bundled Mozilla roots through the public TLS API.
  const trusted = typeof tls.getCACertificates === "function"
    ? tls.getCACertificates("default")
    : tls.rootCertificates;
  return { ...verification, ca: [...trusted, SECTIGO_DV_R36] };
}
